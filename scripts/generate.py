#!/usr/bin/env python3
"""Generate distribution files from global.json; Python 3.9+, no dependencies."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re

REPOSITORY = 'Kxmrg/pocket-qt-site-rules'
RAW = f'https://raw.githubusercontent.com/{REPOSITORY}'


def require(condition, message):
    if not condition:
        raise ValueError(message)


def integer(value, minimum=0, maximum=2147483647):
    return type(value) is int and minimum <= value <= maximum


def metadata(value):
    require(integer(value.get('code'), 1), 'Invalid code')
    require(integer(value.get('publishedAt'), 0, 253402300799), 'Invalid Unix timestamp')
    compatibility = value.get('compatibility', {})
    require(compatibility.get('engine') == 1 and isinstance(compatibility.get('features'), list), 'Invalid compatibility')


def validate(data):
    require(data.get('schemaVersion') == 1 and data.get('type') == 'global', 'Unsupported global format')
    require(data.get('id') == 'pocket-evo.web-rules', 'Invalid global identity')
    metadata(data)
    architectures = data.get('architectures')
    require(isinstance(architectures, dict) and architectures, 'Missing architectures')
    for architecture in architectures.values():
        metadata(architecture)
        require(isinstance(architecture.get('pages'), dict), 'Missing architecture pages')
    require(isinstance(data.get('sites'), list), 'Missing sites')
    ids, domains = set(), set()
    for site in data['sites']:
        require(site.get('schemaVersion') == 1 and site.get('type') == 'site', 'Invalid site envelope')
        metadata(site)
        sid = site.get('id', '')
        require(isinstance(sid, str) and re.fullmatch(r'[a-z0-9][a-z0-9_-]*', sid), 'Unsafe site ID')
        require(sid not in ids, 'Duplicate site ID: ' + sid)
        ids.add(sid)
        require(site.get('architecture') in architectures, 'Unknown architecture: ' + sid)
        base = site.get('base', {})
        low, high = base.get('minCode'), base.get('maxCode', 2147483647)
        require(integer(low, 1) and integer(high, 1) and low <= high, 'Invalid base range: ' + sid)
        require(low <= architectures[site['architecture']]['code'] <= high, 'Incompatible base: ' + sid)
        require(isinstance(site.get('patches'), list), 'Missing patches: ' + sid)
        hosts = site.get('domains')
        require(isinstance(hosts, list) and hosts, 'Missing domains: ' + sid)
        for host in hosts:
            require(isinstance(host, str) and len(host) <= 253 and all(re.fullmatch(r'[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?', label) for label in host.split('.')), 'Invalid domain: ' + sid)
            require(host not in domains, 'Duplicate domain: ' + host)
            domains.add(host)


def encoded(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + '\n').encode('utf-8')


def date(timestamp):
    return datetime.fromtimestamp(timestamp, timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')


def generate(root, check=False):
    raw = root.joinpath('global.json').read_bytes()
    data = json.loads(raw)
    validate(data)
    tag = f"rules-v{data['code']}"
    files = {}

    def record(document, path, content):
        return {
            'id': document['id'], 'schemaVersion': document['schemaVersion'],
            'code': document['code'], 'publishedAt': document['publishedAt'],
            'compatibility': document['compatibility'], 'path': path,
            'url': f'{RAW}/{tag}/{path}', 'size': len(content),
            'sha256': hashlib.sha256(content).hexdigest(),
        }

    manifest = {
        'schemaVersion': 1, 'release': tag, 'publishedAt': data['publishedAt'],
        'global': record(data, 'global.json', raw), 'sites': [],
    }
    rows = []
    for site in sorted(data['sites'], key=lambda s: s['id']):
        path = f"sites/{site['id']}.json"
        content = encoded(site)
        files[path] = content
        item = record(site, path, content)
        item.update(architecture=site['architecture'], domains=site['domains'], base=site['base'])
        manifest['sites'].append(item)
        rows.append(f"| `{site['id']}` | {'、'.join(site['domains'])} | {site['architecture']} | version {site['code']} | {date(site['publishedAt'])} | [下载]({item['url']}) |")
    files['manifest.json'] = encoded(manifest)
    files['README.md'] = (f'''<!-- Generated by scripts/generate.py. Do not edit directly. -->
# Pocket Evo 站点规则

Pocket Evo 的全局站点规则与站点补充规则，用于 HTML 站点的解析与适配。

- 全局规则：**version {data['code']}**
- 规则发布时间：**{date(data['publishedAt'])}**（Unix 秒时间戳；不是脚本运行时间）
- 当前规则架构：**{', '.join(sorted(data['architectures']))}**
- 站点补充规则：**{len(data['sites'])} 个**

## 下载地址

- [全局规则 global.json]({manifest['global']['url']})
- [最新更新索引 manifest.json]({RAW}/main/manifest.json)
- [站点补充规则目录](sites/)

全局文件用于「设置 → 站点规则」导入；站点文件用于「站点适配诊断 → 导入站点规则」。
当前 App 使用文件导入；App 在线检查更新将另行接入，仓库提供文件不代表 App 已支持在线更新。

独立 API 站点由 App 内置客户端处理，不通过本仓库更新。GZ、U3D 尚未包含在当前规则中。
下表按补充规则列出，不是所有可使用通用规则的站点全集，也不代表站点当前可访问或本次重新实测。

## 适配列表

| 站点 ID | 域名 | 架构 | 版本 | 规则发布时间 | 补充规则 |
| --- | --- | --- | --- | --- | --- |
''' + '\n'.join(rows) + '''

## 维护与发布

`global.json` 是唯一规则维护源。`sites/*.json`、`manifest.json` 和本 README 自动生成，不单独编辑。
同一站点在全局和独立文件中的 JSON 内容完全一致；不包含账号、Cookie、API Key 或网页采样。

```sh
python3 scripts/generate.py
python3 scripts/generate.py --check
python3 -m unittest discover -s tests -v
```

规则更新时递增全局 `code` 并更新 `publishedAt`；改动的架构及站点也分别递增自身 `code` 和时间。
只比较同一身份下的 `code`；时间仅展示。结构兼容性由 `schemaVersion`、`compatibility` 和站点 `base` 决定。
生成器检查分发结构和一致性；解析器语义与补丁编译需在 Pocket Evo 项目使用生产规则引擎回归后再发布。

发布前运行上述检查，将全部文件提交，再创建与索引一致的标签：

```sh
# N 替换为 global.json 的 code；标签只创建一次，禁止移动或覆盖
 git tag rules-vN
 git push --atomic origin main rules-vN
```

索引从 main 获取，规则下载地址固定到对应发布标签。必须原子推送分支与标签，避免索引先上线而文件尚不可用。
历史发布标签保留不变；SHA-256 和字节数用于下载完整性校验，不代替数字签名。
详细索引契约见 [MANIFEST.md](MANIFEST.md)。CI 会拒绝自动生成文件与源规则不一致的提交。
''').encode('utf-8')
    stale = set(root.glob('sites/*.json')) - {root / p for p in files if p.startswith('sites/')}
    drift = [p for p, b in files.items() if not (root / p).is_file() or (root / p).read_bytes() != b]
    if check:
        require(not stale and not drift, 'Generated files differ; run python3 scripts/generate.py')
    else:
        for path in stale:
            path.unlink()
        for path, content in files.items():
            target = root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
    return manifest


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        result = generate(Path(__file__).resolve().parents[1], args.check)
        print(f"Validated {result['release']}: {len(result['sites'])} site rules")
    except (ValueError, KeyError, TypeError) as error:
        parser.exit(1, f'Error: {error}\n')
